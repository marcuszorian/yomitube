"""Writes app/src/fork/res/values*/yomitube_strings.xml: NewPipe's own strings (each locale's
translation) for the keys that name the running app, with NewPipe -> YomiTube. Strings that credit
the NewPipe project (About, licence, privacy policy, donations) are deliberately not included.
Re-run after upstream merges:  python3 -I app/src/fork/make_strings.py app/src"""
import os, re, sys, glob
SRC = sys.argv[1]
KEYS = [
    "notification_channel_name", "notification_channel_description",
    "clear_cookie_summary", "error_report_notification_title", "msg_running",
    "error_postprocessing_stopped", "feed_load_error_terminated", "content_not_supported",
    "soundcloud_go_plus_content", "private_content", "youtube_music_premium_content",
    "paid_content", "restricted_video_no_stream", "feed_use_dedicated_fetch_method_help_text",
]
STRING = re.compile(r'<string name="([^"]+)"[^>]*>(.*?)</string>', re.S)
written = 0
for path in sorted(glob.glob(f"{SRC}/main/res/values*/strings.xml")):
    folder = os.path.basename(os.path.dirname(path))
    found = {m.group(1): m.group(0) for m in STRING.finditer(open(path, encoding="utf-8").read())}
    out = [found[k].replace("NewPipe", "YomiTube") for k in KEYS
           if k in found and "NewPipe" in found[k]]
    if not out:
        continue
    os.makedirs(f"{SRC}/fork/res/{folder}", exist_ok=True)
    with open(f"{SRC}/fork/res/{folder}/yomitube_strings.xml", "w", encoding="utf-8") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n'
                '<!-- Generated by app/src/fork/make_strings.py; do not edit by hand. -->\n'
                '<resources xmlns:tools="http://schemas.android.com/tools">\n')
        for s in out:
            f.write("    " + s.replace('<string ', '<string tools:ignore="MissingTranslation" ', 1) + "\n")
        f.write("</resources>\n")
    written += 1
print("locales written:", written)
