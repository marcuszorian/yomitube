package org.schabi.newpipe.mining;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertTrue;

import org.junit.Test;

import java.util.List;

public class SubtitleParserTest {

    private static void assertCue(Cue c, long start, long end, String text) {
        assertEquals("start of " + c, start, c.startMs);
        assertEquals("end of " + c, end, c.endMs);
        assertEquals(text, c.text);
    }

    private static void assertNoOverlap(List<Cue> cues) {
        for (int i = 0; i + 1 < cues.size(); i++) {
            assertTrue("overlap " + cues.get(i) + " / " + cues.get(i + 1),
                    cues.get(i).endMs <= cues.get(i + 1).startMs);
        }
    }

    @Test
    public void srtBasic() {
        String srt = "﻿1\r\n00:00:01,000 --> 00:00:03,500\r\n<i>こんにちは</i>\r\n世界\r\n\r\n"
                + "2\r\n00:00:04,000 --> 00:00:05,000\r\nTom &amp; Jerry &lt;3\r\nsecond line\r\n\r\n"
                + "3\r\n00:00:06,000 --> 00:00:07,000\r\n{\\an8}<font color=\"#fff\">上</font>\r\n";
        List<Cue> cues = SubtitleParser.parse(srt, "srt");
        assertEquals(3, cues.size());
        assertCue(cues.get(0), 1000, 3500, "こんにちは世界");
        assertCue(cues.get(1), 4000, 5000, "Tom & Jerry <3 second line");
        assertCue(cues.get(2), 6000, 7000, "上");
    }

    @Test
    public void srtUnsortedAndOverlappingIsSortedAndClipped() {
        String srt = "2\n00:00:05,000 --> 00:00:06,000\nB\n\n1\n00:00:01,000 --> 00:00:09,000\nA\n";
        List<Cue> cues = SubtitleParser.parse(srt, null);
        assertEquals(2, cues.size());
        assertCue(cues.get(0), 1000, 5000, "A");
        assertCue(cues.get(1), 5000, 6000, "B");
    }

    @Test
    public void vttWithTagsEntitiesAndSettings() {
        String vtt = "WEBVTT\nKind: captions\nLanguage: ja\n\n"
                + "NOTE a comment --> not a cue\n\n"
                + "STYLE\n::cue { color: red }\n\n"
                + "intro\n00:01.000 --> 00:02.500 align:start position:0%\n"
                + "<v Speaker>今日は</v> <b>いい</b>天気&nbsp;ですね&#x3002;\n\n"
                + "00:00:03.000 --> 00:00:04.000\n<ruby>漢字<rt>かんじ</rt></ruby>&quot;q&quot;\n2行目\n";
        List<Cue> cues = SubtitleParser.parse(vtt, "text/vtt");
        assertEquals(2, cues.size());
        assertCue(cues.get(0), 1000, 2500, "今日は いい天気 ですね。");
        assertCue(cues.get(1), 3000, 4000, "漢字\"q\" 2行目"); // ruby readings dropped
    }

    /** Typical YouTube auto-generated VTT: rolling 2-line cues + 10ms snapshot cues. */
    @Test
    public void vttYoutubeRollingAutoCaptionsAreDeduplicated() {
        String vtt = "WEBVTT\nKind: captions\nLanguage: ja\n\n"
                + "00:00:00.320 --> 00:00:02.990 align:start position:0%\n"
                + " \n"
                + "こんにちは<00:00:00.800><c>皆さん</c>\n\n"
                + "00:00:02.990 --> 00:00:03.000 align:start position:0%\n"
                + "こんにちは皆さん\n"
                + " \n\n"
                + "00:00:03.000 --> 00:00:05.430 align:start position:0%\n"
                + "こんにちは皆さん\n"
                + "今日は<00:00:03.500><c>雨</c><00:00:04.000><c>です</c>\n\n"
                + "00:00:05.430 --> 00:00:05.440 align:start position:0%\n"
                + "今日は雨です\n"
                + " \n\n"
                + "00:00:05.440 --> 00:00:07.000 align:start position:0%\n"
                + "今日は雨です\n"
                + "また<00:00:06.000><c>明日</c>\n";
        List<Cue> cues = SubtitleParser.parse(vtt, "vtt");
        assertEquals(cues.toString(), 3, cues.size());
        assertCue(cues.get(0), 320, 2990, "こんにちは皆さん");
        assertCue(cues.get(1), 3000, 5430, "今日は雨です");
        assertCue(cues.get(2), 5440, 7000, "また明日");
        assertNoOverlap(cues);
    }

    /** YouTube srv3 for an auto-generated track: word segments, overlapping windows, append rows. */
    @Test
    public void srv3AutoGenerated() {
        String xml = "<?xml version=\"1.0\" encoding=\"utf-8\" ?><timedtext format=\"3\">\n"
                + "<head><ws id=\"0\"/><wp id=\"0\"/><p t=\"0\">ignored head p</p></head>\n<body>\n"
                + "<w t=\"0\" id=\"1\" wp=\"1\" ws=\"1\"/>\n"
                + "<p t=\"320\" d=\"4680\" w=\"1\"><s ac=\"0\">こんにちは</s><s t=\"480\" ac=\"0\">皆さん</s></p>\n"
                + "<p t=\"2990\" d=\"2010\" w=\"1\" a=\"1\">\n</p>\n"
                + "<p t=\"3000\" d=\"4000\" w=\"1\"><s ac=\"0\">今日は</s><s t=\"500\" ac=\"0\">雨</s><s t=\"1000\">です</s></p>\n"
                + "<p t=\"7000\" d=\"1000\" w=\"1\"><s>A&amp;B &#39;x&#39;</s></p>\n"
                + "</body></timedtext>";
        List<Cue> cues = SubtitleParser.parse(xml, "srv3");
        assertEquals(cues.toString(), 3, cues.size());
        assertCue(cues.get(0), 320, 3000, "こんにちは皆さん");
        assertCue(cues.get(1), 3000, 7000, "今日は雨です");
        assertCue(cues.get(2), 7000, 8000, "A&B 'x'");
        assertNoOverlap(cues);
    }

    @Test
    public void srv3ManualMultiLine() {
        String xml = "<timedtext format=\"3\"><body>"
                + "<p t=\"1000\" d=\"2000\">一行目\n二行目</p>"
                + "<p t=\"3500\" d=\"1000\">Hello<br/>world</p>"
                + "</body></timedtext>";
        List<Cue> cues = SubtitleParser.parse(xml, null); // sniffed
        assertEquals(2, cues.size());
        assertCue(cues.get(0), 1000, 3000, "一行目二行目");
        assertCue(cues.get(1), 3500, 4500, "Hello world");
    }

    @Test
    public void ttml() {
        String xml = "<?xml version=\"1.0\"?><tt xmlns=\"http://www.w3.org/ns/ttml\"><head><styling/></head>"
                + "<body><div>"
                + "<p begin=\"00:00:01.000\" end=\"00:00:02.000\">あ<br />い</p>"
                + "<p begin=\"2.5s\" dur=\"1s\"><span tts:color=\"white\">う</span></p>"
                + "</div></body></tt>";
        List<Cue> cues = SubtitleParser.parse(xml, "ttml");
        assertEquals(2, cues.size());
        assertCue(cues.get(0), 1000, 2000, "あい");
        assertCue(cues.get(1), 2500, 3500, "う");
    }

    @Test
    public void srv1() {
        String xml = "<transcript><text start=\"1.5\" dur=\"2\">foo &amp;amp; bar</text></transcript>";
        List<Cue> cues = SubtitleParser.parse(xml, null);
        assertEquals(1, cues.size());
        // srv1 is double-escaped; one level of decoding leaves "&amp;" — acceptable for a legacy format.
        assertCue(cues.get(0), 1500, 3500, "foo &amp; bar");
    }

    @Test
    public void identicalAdjacentCuesMerged() {
        String srt = "1\n00:00:01,000 --> 00:00:02,000\nX\n\n2\n00:00:02,000 --> 00:00:03,000\nX\n";
        List<Cue> cues = SubtitleParser.parse(srt, "srt");
        assertEquals(1, cues.size());
        assertCue(cues.get(0), 1000, 3000, "X");
    }

    @Test
    public void srtRoundTrip() {
        String srt = "1\n00:00:01,000 --> 01:02:03,004\nあいう\n\n2\n01:02:04,000 --> 01:02:05,000\nB\n";
        List<Cue> cues = SubtitleParser.parse(srt, "srt");
        String out = SubtitleParser.toSrt(cues);
        assertTrue(out, out.contains("00:00:01,000 --> 01:02:03,004\nあいう\n"));
        List<Cue> again = SubtitleParser.parse(out, "srt");
        assertEquals(cues.size(), again.size());
        assertEquals(cues.get(1).startMs, again.get(1).startMs);
    }

    @Test
    public void emptyAndGarbage() {
        assertTrue(SubtitleParser.parse("", null).isEmpty());
        assertTrue(SubtitleParser.parse(null, "srt").isEmpty());
        assertTrue(SubtitleParser.parse("not a subtitle", "srt").isEmpty());
    }
}
