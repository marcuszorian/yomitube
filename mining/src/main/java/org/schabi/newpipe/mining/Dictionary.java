package org.schabi.newpipe.mining;

import android.content.Context;
import android.content.pm.PackageInfo;
import android.content.pm.PackageManager;
import android.database.Cursor;
import android.database.sqlite.SQLiteDatabase;
import android.util.Log;

import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;

/**
 * JMdict (full jmdict-eng, via jmdict-simplified) lookup backed by the SQLite asset
 * {@code assets/jmdict.db}, generated by {@code tools/build_jmdict.py}.
 *
 * <h3>Threading / initialisation</h3>
 * On first use after install/update the ~31 MB asset is copied to {@code noBackupFilesDir}
 * (APK assets are compressed, so SQLite cannot open them in place); this takes up to a couple of
 * seconds. Call {@link #warmUp()} on a background thread early. {@link #lookup} blocks until the
 * database is open, so call it off the main thread (each lookup itself is a single indexed query,
 * well under a millisecond, once open). The instance is thread-safe.
 */
public final class Dictionary implements DictionarySource {
    private static final String TAG = "MiningDictionary";
    private static final String ASSET = "jmdict.db";
    private static final String QUERY =
            "SELECT f.entry_id, coalesce(f.headword, f.text), coalesce(f.reading, f.text), f.prio, e.senses"
                    + " FROM form f JOIN entry e ON e.id = f.entry_id"
                    + " WHERE f.text = ? ORDER BY f.prio, f.entry_id LIMIT 20";

    private static volatile Dictionary instance;

    private final Context context;
    private volatile SQLiteDatabase db;

    private Dictionary(Context context) {
        this.context = context.getApplicationContext();
    }

    /** Cheap; does not open the database. */
    public static Dictionary get(Context context) {
        Dictionary d = instance;
        if (d == null) {
            synchronized (Dictionary.class) {
                d = instance;
                if (d == null) {
                    d = new Dictionary(context);
                    instance = d;
                }
            }
        }
        return d;
    }

    /** Copies the asset if needed and opens the database. Call on a background thread. */
    public void warmUp() {
        open();
    }

    public boolean isReady() {
        return db != null;
    }

    private SQLiteDatabase open() {
        SQLiteDatabase d = db;
        if (d != null) return d;
        synchronized (this) {
            if (db == null) {
                try {
                    File file = ensureCopied();
                    db = SQLiteDatabase.openDatabase(file.getPath(), null,
                            SQLiteDatabase.OPEN_READONLY | SQLiteDatabase.NO_LOCALIZED_COLLATORS);
                } catch (IOException e) {
                    throw new IllegalStateException("Cannot install JMdict database", e);
                }
            }
            return db;
        }
    }

    /** Copies the asset once per installed APK (keyed by lastUpdateTime + versionCode). */
    private File ensureCopied() throws IOException {
        File dir = context.getNoBackupFilesDir();
        File file = new File(dir, ASSET);
        File stamp = new File(dir, ASSET + ".stamp");
        String want = installStamp();
        if (file.exists() && want.equals(readSmall(stamp))) return file;

        Log.i(TAG, "Copying " + ASSET + " from assets");
        File tmp = new File(dir, ASSET + ".tmp");
        try (InputStream in = context.getAssets().open(ASSET);
             OutputStream out = new FileOutputStream(tmp)) {
            byte[] buf = new byte[256 * 1024];
            int n;
            while ((n = in.read(buf)) > 0) out.write(buf, 0, n);
        }
        if (file.exists() && !file.delete()) throw new IOException("Cannot replace " + file);
        if (!tmp.renameTo(file)) throw new IOException("Cannot rename " + tmp);
        try (OutputStream out = new FileOutputStream(stamp)) {
            out.write(want.getBytes("UTF-8"));
        }
        return file;
    }

    private String installStamp() {
        try {
            PackageInfo pi = context.getPackageManager().getPackageInfo(context.getPackageName(), 0);
            return pi.lastUpdateTime + ":" + pi.versionCode;
        } catch (PackageManager.NameNotFoundException e) {
            return "unknown";
        }
    }

    private static String readSmall(File f) {
        if (!f.exists()) return null;
        try (InputStream in = new java.io.FileInputStream(f)) {
            byte[] b = new byte[(int) Math.min(f.length(), 256)];
            int n = in.read(b);
            return n <= 0 ? "" : new String(b, 0, n, "UTF-8");
        } catch (IOException e) {
            return null;
        }
    }

    @Override
    public List<DictEntry> lookup(String term) {
        if (term == null) return Collections.emptyList();
        term = term.trim();
        if (term.isEmpty()) return Collections.emptyList();
        List<DictEntry> out = new ArrayList<>();
        try (Cursor c = open().rawQuery(QUERY, new String[]{term})) {
            while (c.moveToNext()) {
                out.add(new DictEntry(c.getLong(0), c.getString(1), c.getString(2), c.getInt(3),
                        DictEntry.parseSenses(c.getString(4))));
            }
        }
        return out;
    }

    /** Text for the Anki Glossary field; see {@link Glossary#format}. */
    public static String formatGlossary(DictEntry e) {
        return Glossary.format(e);
    }
}
