package org.schabi.newpipe.mining;

import java.io.Serializable;
import java.util.Locale;

/** One caption track offered by YouTube for a video. Immutable, no Android dependencies. */
public final class SubtitleTrackInfo implements Serializable {
    /** BCP-47-ish language code as reported by YouTube, e.g. "ja", "ja-JP", "en". */
    public final String languageCode;
    /** Human-readable name, e.g. "日本語" or "日本語 (自動生成)". */
    public final String displayName;
    public final boolean autoGenerated;
    /** URL to fetch the caption content from. */
    public final String url;
    /** Format hint for {@link SubtitleParser#parse(String, String)}, e.g. "srv3". */
    public final String format;

    public SubtitleTrackInfo(String languageCode, String displayName, boolean autoGenerated,
                             String url, String format) {
        this.languageCode = languageCode;
        this.displayName = displayName;
        this.autoGenerated = autoGenerated;
        this.url = url;
        this.format = format;
    }

    /** True for "ja", "ja-JP", "ja_JP", "JA" etc. */
    public boolean isJapanese() {
        return isJapaneseCode(languageCode);
    }

    public static boolean isJapaneseCode(String code) {
        if (code == null) return false;
        String c = code.trim().toLowerCase(Locale.ROOT);
        return c.equals("ja") || c.equals("jpn") || c.startsWith("ja-") || c.startsWith("ja_");
    }

    @Override
    public String toString() {
        return "SubtitleTrackInfo[" + languageCode + (autoGenerated ? " auto" : "") + " '"
                + displayName + "' " + format + "]";
    }
}
