package org.schabi.newpipe.mining;

import org.schabi.newpipe.extractor.MediaFormat;
import org.schabi.newpipe.extractor.NewPipe;
import org.schabi.newpipe.extractor.downloader.Response;
import org.schabi.newpipe.extractor.exceptions.ExtractionException;
import org.schabi.newpipe.extractor.stream.AudioStream;
import org.schabi.newpipe.extractor.stream.AudioTrackType;
import org.schabi.newpipe.extractor.stream.DeliveryMethod;
import org.schabi.newpipe.extractor.stream.SubtitlesStream;

import java.io.IOException;
import java.util.ArrayList;
import java.util.List;

/**
 * Picks the Japanese caption track and the audio stream to clip from, and fetches captions.
 *
 * <p>Inside NewPipe the playing {@code StreamInfo} is already known, so there is no searching:
 * callers pass its subtitle and audio stream lists. NewPipe has already initialised the
 * extractor's downloader.
 *
 * <p><b>{@link #fetchCues} blocks — never call it on the main thread.</b>
 */
public final class CaptionRepository {

    /** Caption format requested from YouTube. See {@link SubtitleParser} for why srv3. */
    static final MediaFormat CAPTION_FORMAT = MediaFormat.TRANSCRIPT3;
    static final String CAPTION_FORMAT_HINT = SubtitleParser.FORMAT_SRV3;

    private CaptionRepository() {
    }

    /**
     * Converts NewPipe's subtitle streams to tracks, keeping only the srv3 variants (YouTube
     * offers each language in several formats).
     */
    public static List<SubtitleTrackInfo> tracksOf(List<SubtitlesStream> streams) {
        List<SubtitleTrackInfo> tracks = new ArrayList<>();
        if (streams == null) return tracks;
        for (SubtitlesStream s : streams) {
            if (s == null || s.getFormat() != CAPTION_FORMAT || !s.isUrl()) continue;
            tracks.add(new SubtitleTrackInfo(s.getLanguageTag(), s.getDisplayLanguageName(),
                    s.isAutoGenerated(), s.getContent(), CAPTION_FORMAT_HINT));
        }
        return tracks;
    }

    /** Fetches and parses a caption track. Blocking. */
    public static List<Cue> fetchCues(SubtitleTrackInfo track) throws IOException {
        try {
            Response r = NewPipe.getDownloader().get(track.url);
            if (r.responseCode() >= 400) {
                throw new IOException("Caption fetch failed: HTTP " + r.responseCode());
            }
            String body = r.responseBody();
            if (body == null || body.isEmpty()) {
                throw new IOException("Caption fetch returned an empty body");
            }
            return SubtitleParser.parse(body, track.format);
        } catch (ExtractionException e) { // ReCaptchaException
            throw new IOException("Caption fetch blocked: " + e.getMessage(), e);
        }
    }

    // ------------------------------------------------------------------ pure logic (unit-tested)

    /**
     * Track priority from the plan: (1) manual Japanese, (2) auto-generated Japanese, (3) null.
     * Among equals, an exact "ja" code beats regional variants; otherwise list order is kept.
     */
    public static SubtitleTrackInfo selectTrack(List<SubtitleTrackInfo> tracks) {
        if (tracks == null) return null;
        SubtitleTrackInfo best = null;
        int bestScore = Integer.MIN_VALUE;
        for (SubtitleTrackInfo t : tracks) {
            if (t == null || !t.isJapanese()) continue;
            int score = (t.autoGenerated ? 0 : 10) + ("ja".equalsIgnoreCase(t.languageCode) ? 1 : 0);
            if (score > bestScore) {
                best = t;
                bestScore = score;
            }
        }
        return best;
    }

    /**
     * Picks the audio-only stream to clip from: directly downloadable (progressive HTTP) beats
     * DASH/HLS; original audio track beats dubbed/descriptive; M4A (AAC) beats others; then highest
     * bitrate.
     */
    public static AudioStream selectAudioStream(List<AudioStream> streams) {
        if (streams == null) return null;
        AudioStream best = null;
        long bestScore = Long.MIN_VALUE;
        for (AudioStream a : streams) {
            if (a == null || !a.isUrl()) continue;
            long score = audioScore(a.getDeliveryMethod() == DeliveryMethod.PROGRESSIVE_HTTP,
                    a.getAudioTrackType() == null || a.getAudioTrackType() == AudioTrackType.ORIGINAL,
                    a.getFormat() == MediaFormat.M4A, a.getAverageBitrate());
            if (score > bestScore) {
                best = a;
                bestScore = score;
            }
        }
        return best;
    }

    static long audioScore(boolean progressive, boolean original, boolean m4a, int bitrateKbps) {
        return (progressive ? 1_000_000_000L : 0) + (original ? 100_000_000L : 0)
                + (m4a ? 10_000_000L : 0) + Math.max(0, Math.min(bitrateKbps, 9_999_999));
    }
}
